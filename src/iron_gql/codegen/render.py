def scaffold_claims(
    *,
    gql_fn_name: str,
    base_url_ref: ImportRef,
    scalars: dict[str, ImportRef],
    to_camel_ref: ImportRef,
) -> dict[str, tuple[str, ...]]:
    # Names only imported when a package uses slots or fragments are listed
    # unconditionally: the reserved set must not depend on which optional
    # features a package happens to use today, or adding a slot to it would
    # rebind a name that generated fine a commit earlier.
    #
    # Each binding keeps its origin so the collision rule can tell two
    # scaffold sources fighting over one name apart from one binding listed
    # twice: identical origins (the same import statement reached from two
    # configs, e.g. `import pydantic`) collapse into a single claim, while
    # different origins for one name are a real collision.
    pairs: list[tuple[str, str]] = [
        *((name, "the generated model base class") for name in BASE_CLASS_NAMES),
        *((module, f"import {module}") for module in STDLIB_MODULE_NAMES),
        *((module, f"import {module}") for module in THIRD_PARTY_MODULE_NAMES),
        *((name, f"from contextlib import {name}") for name in CONTEXTLIB_NAMES),
        *((name, f"from collections.abc import {name}") for name in ABC_NAMES),
        *((name, f"from abc import {name}") for name in ABC_MODULE_NAMES),
        *((name, f"from typing import {name}") for name in TYPING_NAMES),
        *((name, f"from iron_gql import {name}") for name in IRON_GQL_NAMES),
        (BOUND_RESULT_PARAM, "the type parameter of a template's bound base"),
        (TMODEL_PARAM, "the model type parameter of every on-type base"),
        (TREADS_PARAM, "the readable-closure type parameter of every on-type base"),
        (gql_fn_name, "the generated gql function"),
        ("_client", "the generated client binding"),
        ("_statement_factories", "the generated statement factory table"),
        (base_url_ref.root_symbol, base_url_ref.import_statement()),
        (to_camel_ref.root_module, f"import {to_camel_ref.root_module}"),
        *((ref.root_module, f"import {ref.root_module}") for ref in scalars.values()),
    ]
    claims: dict[str, dict[str, None]] = {}
    for name, origin in pairs:
        claims.setdefault(name, {})[origin] = None
    return {name: tuple(origins) for name, origins in claims.items()}


def render_field(field: CollectedField) -> str:
    rendered_type = render_type_expr(field.rendered_type)
    default_expr = field.default_expr
    if field.is_conditional and default_expr is None:
        default_expr = "None"

    if field.alias is not None:
        rendered_type = (
            f"Annotated[{rendered_type}, "
            f'pydantic.Field(validation_alias="{field.alias}", '
            f'serialization_alias="{field.alias}")]'
        )
    if default_expr is not None:
        return f"{field.name}: {rendered_type} = {default_expr}"
    return f"{field.name}: {rendered_type}"


def render_pydantic_class(model: CollectedModel, base: str) -> str:
    rendered_fields = "\n".join(render_field(field) for field in model.fields)
    header = f"class {model.name}{_type_params(model.type_params)}({base}):"
    return f"{header}\n    {indent_block(rendered_fields, '    ')}"


def render_slot_class(model: CollectedModel) -> str:
    # A node model is the phantom's one destination: the parameter threaded
    # down the path to it lands here, in the slot base, and each binding fills
    # it with the fragment classes readable at this slot.
    if not model.type_params:
        # Internal invariant: a node model is its own slot's model, and
        # `collect.parametrize_slot_paths` seeds the walk with exactly those.
        msg = f"slot node {model.name!r} reached the renderer unparametrised"
        raise AssertionError(msg)
    offered = ", ".join(model.type_params)
    body = "\n".join([
        f'slot_name__: ClassVar[str] = "{model.slot_name}"',
        *(render_field(field) for field in model.fields),
    ])
    header = (
        f"class {model.name}{_type_params(model.type_params)}"
        f"({SLOT_MODEL_BASE_NAME}[{offered}]):"
    )
    return f"{header}\n    {indent_block(body, '    ')}"


def _type_params(type_params: tuple[str, ...]) -> str:
    # PEP 695 parameters, declared on the model itself: their order is the
    # model's own statement, which a parametrised base cannot make when the
    # model reaches two slots. Variance is left to inference and lands where it
    # belongs -- a parameter that only reaches `slots.GQLSlotNode`'s
    # contravariant phantom infers contravariant, one behind a `list[...]`
    # field infers invariant, and invariant is the truth for a mutable field.
    # Shared code that wants any binding's result spells the phantom `Any`,
    # which is assignable both ways whatever the variance came out as.
    #
    # The parameters are visible in pydantic's JSON Schema -- `$defs` keys and
    # titles carry the fragment class names (`Post_ImageParts_`) -- so two
    # bindings of one template describe the same shape under two names. The
    # phantom is not a field and nothing validates by it; a consumer diffing
    # schema snapshots is the one this shows up for.
    if not type_params:
        return ""
    # Each defaults to `Never` (PEP 696), so the bare `{Op}Result` an
    # annotation may still spell means "readable by nothing" rather than an
    # unparametrised generic -- the same bottom `slots.GQLSlotNode` declares
    # for its own phantom.
    defaulted = ", ".join(f"{name} = Never" for name in type_params)
    return f"[{defaulted}]"


def render_imports(
    to_camel_ref: ImportRef,
    scalars: dict[str, ImportRef],
    base_url_ref: ImportRef,
    mode: ModeConfig,
) -> str:
    import_modules = [ref.module for ref in scalars.values()]
    scalar_imports = "\n".join(f"import {module}" for module in import_modules)
    # Every fixed name is emitted whole, whichever features the package
    # happens to use: the module suppresses unused imports, so an extra line
    # costs nothing, while a predicate that drifts from the emitter that
    # writes the name costs a NameError in generated code -- and
    # `scaffold_claims` already reserves the same names unconditionally for
    # exactly that reason. Only the mode-owned pairs are a choice, and
    # `ModeConfig` is what chooses.
    abc_imports = "\n".join(
        f"from collections.abc import {name}"
        for name in ABC_NAMES
        if name not in GENERATOR_NAMES or name == mode.generator
    )
    abc_module_imports = "\n".join(
        f"from abc import {name}" for name in ABC_MODULE_NAMES
    )
    typing_imports = "\n".join(f"from typing import {name}" for name in TYPING_NAMES)
    iron_gql_imports = "\n".join(
        f"from iron_gql import {name}" for name in IRON_GQL_NAMES
    )
    stdlib_imports = "\n".join(f"import {module}" for module in STDLIB_MODULE_NAMES)
    contextlib_imports = f"from contextlib import {mode.stream_context}"
    third_party_imports = "\n".join(
        f"import {module}" for module in THIRD_PARTY_MODULE_NAMES
    )
    return f"""\
{stdlib_imports}
{abc_module_imports}
{abc_imports}
{contextlib_imports}
{typing_imports}

{third_party_imports}

{iron_gql_imports}

import {to_camel_ref.module}

{scalar_imports}

{base_url_ref.import_statement()}"""


