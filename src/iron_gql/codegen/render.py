def render_header(*, unsafe_multiple_inheritance: bool) -> str:
    # `reportUnsafeMultipleInheritance` выключается только для module с
    # multi-base slot model. Fragment definition всегда наследует один
    # `slots.GQLFragment[Model, Reads]` base и этого suppression не требует.
    suppressions = "reportUnusedImport=false"
    if unsafe_multiple_inheritance:
        suppressions += ", reportUnsafeMultipleInheritance=false"
    return f"""\
from __future__ import annotations
# Code generated by iron_gql, DO NOT EDIT.
# fmt: off
# pyright: {suppressions}
# ruff: noqa"""


# The module-level names the scaffold binds, kept in one place because
# `scaffold_claims` hands the same set to the collision rule and everything
# below renders from these very names. Each tuple is already sorted: the import
# blocks are emitted in this order.
MODEL_BASE_NAME = "GQLModel"
OPEN_MODEL_BASE_NAME = "GQLOpenModel"
SLOT_MODEL_BASE_NAME = "GQLSlotModel"
BASE_CLASS_NAMES = (MODEL_BASE_NAME, OPEN_MODEL_BASE_NAME, SLOT_MODEL_BASE_NAME)
STDLIB_MODULE_NAMES = ("datetime", "typing")
# Imported unconditionally and referenced by every model, so it is reserved
# unconditionally too — deriving the claim from `to_camel_ref` instead would
# drop it as soon as a package points that option somewhere other than pydantic.
THIRD_PARTY_MODULE_NAMES = ("pydantic",)
# Both modes' names are reserved whichever mode a package is generated in: the
# reserved set must not depend on the mode in force today, or switching a
# package to the other mode would rebind a name that generated fine before.
CONTEXTLIB_NAMES = ("AbstractAsyncContextManager", "AbstractContextManager")
GENERATOR_NAMES = ("AsyncGenerator", "Generator")
ABC_NAMES = (*GENERATOR_NAMES, "Callable", "Sequence")
ABC_MODULE_NAMES = ("ABC", "abstractmethod")
# An unfilled slot spells `Never` twice over -- as its node's phantom
# (`render_slot_class`) and as the element type of its `bind()` parameter
# (`EMPTY_SLOT_FORM`). `typing.cast` is the one point where a template's shared
# bound class reconciles the result type `bind()`'s overload promised with the
# one runtime class every combination actually validates against
# (`_render_template_bound_execute`).
TYPING_NAMES = (
    "Annotated",
    "Any",
    "ClassVar",
    "Literal",
    "Never",
    "TypeVar",
    "final",
    "overload",
    "override",
)
IRON_GQL_NAMES = ("runtime", "slots")
# The one name in this block the module never binds: it is a PEP 695 parameter
# written *inside* a template's bound base (`render_template_bases`), where it
# shadows a module-level model or enum spelled the same. `execute`'s variable
# annotations are rendered in that scope, so a schema with an `input TResult`
# used as a template variable makes the base read `TResult` as its own
# parameter while `bind()`'s own overloads read the model -- a package that
# generates cleanly and then fails to type-check. Reserved rather than renamed
# out of the way: every name a parameter could take is a name a schema can
# spell, so only a claim closes the case.
BOUND_RESULT_PARAM = "TResult"
# The two parameters every `On{Type}` base (below) is generic over: one pair
# of module-level TypeVars, reused across every base rather than declared
# fresh per class, mirroring `slots.GQLFragment`'s own `TModel_co`/
# `TReads_contra` and for the same reason (PEP 695 cannot declare variance,
# and the second parameter needs a contravariant `default=Never`). A class
# that merely mentions a free TypeVar in its base expression is generic over
# it without declaring its own -- old-style generics have always worked this
# way -- so every `On{Type}` base ends up parametrised by exactly this pair.
TMODEL_PARAM = "TModel"
TREADS_PARAM = "TReads"


# A slot payload carries every passed fragment's fields next to the static
# selection, and a fragment validates that same payload for its own fields —
# so every model validating inside a slot or fragment subtree ignores the
# keys other readers asked for instead of forbidding them. Isolation is not
# lost: a model exposes only the fields its own selection declared.
OPEN_BASE = f"""\
class {OPEN_MODEL_BASE_NAME}({MODEL_BASE_NAME}):
    model_config = pydantic.ConfigDict(extra="ignore")"""

_SLOT_BASES = f"{OPEN_MODEL_BASE_NAME}, slots.GQLSlotNode[TOffered]"
# `TOffered` is a PEP 695 parameter that does nothing but pass through to the
# contravariant phantom of `slots.GQLSlotNode`, which is where its variance
# comes from: a node offering more fragments stays acceptable where fewer are
# expected. Unlike `BOUND_RESULT_PARAM` it claims nothing: this base's body is
# `pass`, so there is no module-level name it could shadow.
SLOT_BASE = f"""\
class {SLOT_MODEL_BASE_NAME}[TOffered]({_SLOT_BASES}):
    pass"""

# Declared once, ahead of every `On{Type}` base (`render_on_type_bases`),
# which all reuse this exact pair -- see `TMODEL_PARAM`/`TREADS_PARAM`'s own
# comment for why they are module-level TypeVars rather than a PEP 695
# declaration repeated per base.
ON_TYPE_TYPEVARS = f"""\
{TMODEL_PARAM} = TypeVar("{TMODEL_PARAM}", bound=pydantic.BaseModel, covariant=True)
{TREADS_PARAM} = TypeVar("{TREADS_PARAM}", contravariant=True)"""


